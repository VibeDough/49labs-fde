def _f5():
    c = Chart(680, "reader", marker="ce5", aria="四类部署选型方案包定位图")
    c.header("四类部署选型方案包 · 演练归纳", "按「数据敏感度 × 集成复杂度」定位",
             "每格给出适用场景与组合要点；均为教学组合，非厂商推荐或排名")
    w = (c.W - 2 * c.pad - 16) / 2
    x1, x2 = c.pad, c.pad + w + 16
    cards = [
        (x1, "低敏感 · 高集成", "方案 3｜复杂系统集成",
         "Agentic RAG + MCP + 业务系统 · 混合部署", "制造 / 能源 · 多源知识与写入"),
        (x2, "高敏感 · 高集成", "方案 4｜团队工作台",
         "AI 工作台 + 资料库 + 连接器 + 企业权限", "内部提效 / 知识沉淀 · 可私有化"),
        (x1, "低敏感 · 低集成", "方案 1｜轻量起步",
         "公有云 API + 低代码平台 + 托管知识库", "PoC / 非敏感业务 · 追求最快验证"),
        (x2, "高敏感 · 低集成", "方案 2｜强合规私有化",
         "开源权重 + 本地推理 + 私有平台 + AI 网关", "金融 / 政务 · 数据不出域"),
    ]
    h = 96
    for i, (x, tag, title, mid, sub) in enumerate(cards):
        y = c.y + (i // 2) * (h + 16)
        c.rect(x, y, w, h, "ba" if i in (0, 3) else "b")
        c.text(x + 14, y + 20, tag, "k")
        c.text(x + 14, y + 42, title, "t")
        c.text(x + 14, y + 64, mid, "s")
        c.text(x + 14, y + 84, sub, "s")
    c.y += 2 * (h + 16) + 2
    c.note("上排集成复杂度高、下排低；左列数据敏感度低、右列高。详见第九篇 9.4；四个方案包均为教学演练组合，组件能力与合规资质以当期官方文档与客户评审为准。")
